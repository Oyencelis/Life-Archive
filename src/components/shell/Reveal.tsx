"use client";

import { useEffect, useRef, useState, type ReactNode } from "react";

// Fades/rises a section into place the first time it scrolls into view.
// Deliberately CSS-transition-driven (not a JS animation library) so the
// existing global `prefers-reduced-motion` rule in globals.css — which
// zeroes every transition/animation duration site-wide — covers this for
// free, no extra reduced-motion branching needed here.
export function Reveal({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;

    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true);
          observer.disconnect();
        }
      },
      { threshold: 0.12, rootMargin: "0px 0px -60px 0px" }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`ed-reveal${visible ? " ed-reveal-visible" : ""}${className ? ` ${className}` : ""}`}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
    >
      {children}
    </div>
  );
}
